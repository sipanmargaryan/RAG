import os
import subprocess
import sys
from io import StringIO
from pathlib import Path

from alembic.config import Config
from sqlalchemy.engine import make_url

from alembic import command

PROJECT_ROOT = Path(__file__).resolve().parents[1]


def test_offline_migration_creates_pdf_metadata_table():
    output = StringIO()
    config = Config(str(PROJECT_ROOT / "alembic.ini"), output_buffer=output)
    command.upgrade(config, "head", sql=True)
    sql = output.getvalue()
    assert "CREATE TABLE pdf_documents" in sql
    assert "UNIQUE (bucket_name, object_key)" in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql


def test_async_migrations_upgrade_downgrade_and_match_models(postgres_url):
    """Exercise the asyncpg CLI on a disposable PostgreSQL container."""
    url = make_url(postgres_url)
    environment = os.environ.copy()
    environment.update(
        {
            "POSTGRES_HOST": url.host,
            "POSTGRES_PORT": str(url.port),
            "POSTGRES_USER": url.username,
            "POSTGRES_PASSWORD": url.password,
            "POSTGRES_DATABASE": url.database,
        }
    )
    for arguments in (
        ["upgrade", "head"],
        ["check"],
        ["downgrade", "base"],
        ["upgrade", "head"],
        ["check"],
    ):
        result = subprocess.run(
            [sys.executable, "-m", "alembic", *arguments],
            cwd=PROJECT_ROOT,
            env=environment,
            capture_output=True,
            text=True,
            timeout=60,
        )
        assert result.returncode == 0, result.stdout + result.stderr
